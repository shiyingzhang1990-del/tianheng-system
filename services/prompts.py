# 框架映射
FRAMEWORKS = {
    'epic': {
        'name': 'EPIC认知框架',
        'template': EPIC_PROMPT_TEMPLATE,
    },
    'management_world': {
        'name': '管理世界风格',
        'template': MW_PROMPT_TEMPLATE,
    },
}


def get_framework(framework_id: str = 'epic'):
    """获取指定的认知框架"""
    return FRAMEWORKS.get(framework_id, FRAMEWORKS['epic'])


def list_frameworks():
    """列出所有可用框架"""
    return [{'id': k, 'name': v['name']} for k, v in FRAMEWORKS.items()]
